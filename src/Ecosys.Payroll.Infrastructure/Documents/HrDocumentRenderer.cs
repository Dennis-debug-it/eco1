/// <summary>Letters and statements for HR: certificate of service and final-dues statement.</summary>
public static class HrDocumentRenderer
{
    private const float Left = 56, Right = PdfWriter.A4Width - 56;

    /// <summary>The company's letterhead (logo, colour and details, or its own header artwork), then the document title.</summary>
    private static float Letterhead(PdfWriter pdf, LegalEntity entity, string title, Brand brand)
    {
        var y = brand.Draw(pdf, entity, Left, Right);
        if (string.IsNullOrEmpty(title)) return y;
        y += 8;
        pdf.Text(Left, y, title, 13, bold: true, color: brand.TextColour);
        return y + 24;
    }

    /// <summary>Wraps text to the page width; returns the new y.</summary>
    private static float Paragraph(PdfWriter pdf, float y, string text, float size = 10.5f, float width = Right - Left)
    {
        var line = "";
        foreach (var word in text.Split(' '))
        {
            var candidate = line.Length == 0 ? word : line + " " + word;
            if (PdfWriter.Measure(candidate, size) > width && line.Length > 0) { pdf.Text(Left, y, line, size); y += size * 1.5f; line = word; }
            else line = candidate;
        }
        if (line.Length > 0) { pdf.Text(Left, y, line, size); y += size * 1.5f; }
        return y + 6;
    }

    /// <summary>
    /// Certificate of service (Employment Act 2007 s.51): employer, employee, dates and nature of employment.
    /// It deliberately states no reason for leaving and no assessment of conduct.
    /// </summary>
    public static byte[] CertificateOfService(LegalEntity entity, Employee emp, IReadOnlyList<(DateOnly From, DateOnly? To, string? JobTitle)> history, DateOnly issuedOn, string? signatoryName, Brand? brand = null)
    {
        brand ??= Brand.Plain;
        var pdf = new PdfWriter();
        var y = Letterhead(pdf, entity, "CERTIFICATE OF SERVICE", brand);
        pdf.Text(Right, y - 24, $"Date: {issuedOn:dd MMMM yyyy}", 9.5f, align: TextAlign.Right);
        y = Paragraph(pdf, y, "Issued under section 51 of the Employment Act, 2007.", 9, Right - Left);
        y += 6;
        void Row(string k, string v) { pdf.Text(Left, y, k, 10); pdf.Text(Left + 170, y, v, 10, bold: true, maxWidth: Right - Left - 170); y += 18; }
        Row("Name of employer", entity.Name);
        Row("Employer's address", entity.Address ?? "—");
        Row("Name of employee", emp.FullName);
        Row("Employee number", emp.EmployeeNumber);
        Row("National ID / passport", emp.NationalId ?? emp.PassportNumber ?? "—");
        Row("Date of employment", emp.HireDate.ToString("dd MMMM yyyy"));
        Row("Date employment ended", emp.TerminationDate?.ToString("dd MMMM yyyy") ?? "—");
        y += 10;
        pdf.Text(Left, y, "Nature of employment", 10, bold: true);
        y += 16;
        foreach (var (from, to, title) in history.Where(h => !string.IsNullOrWhiteSpace(h.JobTitle)))
        {
            pdf.Text(Left + 12, y, $"{from:dd MMM yyyy} – {(to is { } t ? t.ToString("dd MMM yyyy") : emp.TerminationDate?.ToString("dd MMM yyyy") ?? "date")}", 10);
            pdf.Text(Left + 210, y, title!, 10, maxWidth: Right - Left - 210);
            y += 15;
        }
        y += 20;
        y = Paragraph(pdf, y, $"This is to certify that the above-named was employed by {entity.Name} for the period and in the capacity stated above.");
        y += 50;
        pdf.Line(Left, y, Left + 200, y, 0.6f);
        y += 14;
        pdf.Text(Left, y, signatoryName ?? "Authorised signatory", 10);
        y += 13;
        pdf.Text(Left, y, "For and on behalf of " + entity.Name, 9);
        brand.DrawFooter(pdf, Left, Right);
        pdf.Text(Left, PdfWriter.A4Height - 40, "Generated by Ecosys Payroll. Verify authenticity with the employer's HR department.", 7.5f);
        return pdf.ToBytes();
    }

    public static byte[] FinalDuesStatement(LegalEntity entity, Employee emp, Separation s, string currency, Brand? brand = null)
    {
        brand ??= Brand.Plain;
        var pdf = new PdfWriter();
        var y = Letterhead(pdf, entity, "FINAL DUES STATEMENT", brand);
        var d = s.Dues ?? new FinalDues();
        void Kv(string k, string v) { pdf.Text(Left, y, k, 9.5f); pdf.Text(Left + 150, y, v, 9.5f, bold: true); y += 14; }
        Kv("Employee", $"{emp.FullName} ({emp.EmployeeNumber})");
        Kv("Exit type", s.Type.ToString());
        Kv("Notice date / last day", $"{s.NoticeDate:dd MMM yyyy} / {s.LastWorkingDay:dd MMM yyyy}");
        Kv("Completed years of service", d.CompletedYearsOfService.ToString());
        Kv("Monthly basic salary", $"{currency} {d.MonthlyBasic:N2}");
        Kv("Status", s.Status.ToString());
        y += 12;
        pdf.Rect(Left, y, Right - Left, 16, 0.88f);
        pdf.Text(Left + 6, y + 11.5f, "Item", 9, true);
        pdf.Text(Right - 6, y + 11.5f, "Amount", 9, true, TextAlign.Right);
        y += 16;
        foreach (var l in d.Lines)
        {
            y += 13;
            pdf.Text(Left + 6, y, l.Description, 9.5f, maxWidth: Right - Left - 110);
            pdf.Text(Right - 6, y, l.Amount.ToString("N2"), 9.5f, align: TextAlign.Right);
            y += 11;
            pdf.Text(Left + 14, y, l.Working, 7.5f, maxWidth: Right - Left - 30);
            y += 4;
            pdf.Line(Left, y, Right, y, 0.3f, 0.8f);
        }
        y += 16;
        pdf.Text(Left + 6, y, "Total earnings", 10, true); pdf.Text(Right - 6, y, d.TotalEarnings.ToString("N2"), 10, true, TextAlign.Right); y += 15;
        pdf.Text(Left + 6, y, "Total recoveries", 10, true); pdf.Text(Right - 6, y, (-d.TotalRecoveries).ToString("N2"), 10, true, TextAlign.Right); y += 22;
        foreach (var n in d.Notes) y = Paragraph(pdf, y, "• " + n, 8.5f);
        brand.DrawFooter(pdf, Left, Right);
        pdf.Text(Left, PdfWriter.A4Height - 40, $"Statutory deductions are applied in the final payroll for the period ending {d.PayableInPeriodEnding:dd MMM yyyy}. Generated {DateTime.UtcNow:dd MMM yyyy HH:mm} UTC.", 7.5f);
        return pdf.ToBytes();
    }

    /// <summary>
    /// Offer letter on the company letterhead. <paramref name="body"/> is the filled-in text: a blank line starts a
    /// paragraph, "## " a heading and "- " a bullet. A draft carries a DRAFT mark; an accepted letter carries the
    /// candidate's electronic acceptance.
    /// </summary>
    public static byte[] OfferLetter(LegalEntity entity, OfferLetter letter, string candidateName, string candidateEmail, DateOnly issuedOn, bool draft, Brand? brand = null)
    {
        brand ??= Brand.Plain;
        var pdf = new PdfWriter();
        const float size = 10.5f, lineGap = size * 1.45f;
        var bottom = PdfWriter.A4Height - (string.IsNullOrWhiteSpace(brand.Footer) ? 70 : 84);
        var page = 1;
        void Footer()
        {
            brand.DrawFooter(pdf, Left, Right);
            pdf.Text(Left, PdfWriter.A4Height - 40, $"{letter.Reference} · Private and confidential", 7.5f);
            pdf.Text(Right, PdfWriter.A4Height - 40, $"Page {page}", 7.5f, align: TextAlign.Right);
            if (draft) pdf.Text((Left + Right) / 2, PdfWriter.A4Height - 40, "DRAFT: NOT SENT", 9, bold: true, TextAlign.Center);
        }
        var y = Letterhead(pdf, entity, "", brand);
        pdf.Text(Right, y, $"Date: {issuedOn:d MMMM yyyy}", 10, align: TextAlign.Right);
        pdf.Text(Right, y + 13, $"Ref: {letter.Reference}", 9, align: TextAlign.Right);
        pdf.Text(Left, y, "PRIVATE AND CONFIDENTIAL", 9, bold: true);
        y += 18;
        pdf.Text(Left, y, candidateName, 10.5f, bold: true); y += 13;
        pdf.Text(Left, y, candidateEmail, 9.5f); y += 26;
        Footer();

        void Ensure(float needed)
        {
            if (y + needed <= bottom) return;
            pdf.NewPage(); page++; y = 60; Footer();
        }
        void Wrapped(string text, float x, float width, bool bold = false, float fontSize = size, PdfColor? color = null)
        {
            var line = "";
            foreach (var word in text.Split(' ', StringSplitOptions.RemoveEmptyEntries))
            {
                var candidate = line.Length == 0 ? word : line + " " + word;
                if (PdfWriter.Measure(candidate, fontSize, bold) > width && line.Length > 0) { Ensure(lineGap); pdf.Text(x, y, line, fontSize, bold, color: color); y += lineGap; line = word; }
                else line = candidate;
            }
            if (line.Length > 0) { Ensure(lineGap); pdf.Text(x, y, line, fontSize, bold, color: color); y += lineGap; }
        }

        Wrapped(letter.Subject, Left, Right - Left, bold: true, fontSize: 11.5f, color: brand.TextColour);
        y += 6;
        foreach (var block in Blocks(letter.Body))
        {
            switch (block.Kind)
            {
                case 'h': y += 4; Ensure(lineGap * 2); Wrapped(block.Text, Left, Right - Left, bold: true, fontSize: 11); break;
                case '-': Ensure(lineGap); pdf.Text(Left + 8, y, "•", size); Wrapped(block.Text, Left + 22, Right - Left - 22); y += 1; break;
                default: Wrapped(block.Text, Left, Right - Left); y += 7; break;
            }
        }

        // Signature.
        y += 14; Ensure(90);
        pdf.Text(Left, y, "Yours sincerely,", size); y += 44;
        pdf.Line(Left, y, Left + 200, y, 0.6f); y += 14;
        pdf.Text(Left, y, letter.SignatoryName ?? "Authorised signatory", size, bold: true); y += 13;
        if (!string.IsNullOrWhiteSpace(letter.SignatoryTitle)) { pdf.Text(Left, y, letter.SignatoryTitle, 9.5f); y += 13; }
        pdf.Text(Left, y, "For and on behalf of " + entity.Name, 9.5f); y += 30;

        // Acceptance.
        Ensure(110);
        pdf.Line(Left, y, Right, y, 0.5f, 0.6f); y += 18;
        pdf.Text(Left, y, "ACCEPTANCE", 10, bold: true); y += 16;
        if (letter.Status == OfferLetterStatus.Accepted && letter.RespondedAt is { } at)
        {
            Wrapped($"I, {letter.ResponseName}, accept this offer of employment on the terms set out above.", Left, Right - Left);
            var how = letter.RecordedByHr ? $"Acceptance recorded by {letter.ResponseName} on behalf of the candidate" : $"Accepted electronically by {letter.ResponseName}";
            Wrapped($"{how} on {BusinessClock.ToLocal(at):d MMMM yyyy 'at' HH:mm} {BusinessClock.Abbreviation}{(string.IsNullOrWhiteSpace(letter.ResponseIp) ? "" : $" from {letter.ResponseIp}")}.", Left, Right - Left, fontSize: 9);
        }
        else
        {
            Wrapped($"I, {candidateName}, accept this offer of employment on the terms set out above.", Left, Right - Left);
            y += 30;
            pdf.Line(Left, y, Left + 200, y, 0.6f); pdf.Line(Left + 260, y, Left + 400, y, 0.6f); y += 13;
            pdf.Text(Left, y, "Signature", 9); pdf.Text(Left + 260, y, "Date", 9);
        }
        return pdf.ToBytes();
    }

    /// <summary>A short sample letter to preview the letterhead.</summary>
    public static byte[] SampleLetter(LegalEntity entity, Brand brand)
    {
        var pdf = new PdfWriter();
        var y = Letterhead(pdf, entity, "", brand);
        pdf.Text(Right, y, $"Date: {BusinessClock.Today():d MMMM yyyy}", 10, align: TextAlign.Right);
        y += 30;
        pdf.Text(Left, y, "Sample letter", 11.5f, bold: true, color: brand.TextColour); y += 20;
        foreach (var p in new[]
        {
            "This is how your letterhead looks on letters from Ecosys Payroll: offer letters, certificates of service and final dues statements. Payslips carry the logo and colour in a compact header.",
            "Check that the logo is sharp, the colours match your brand, and your address and contact details are correct. Letters already sent keep the letterhead they were sent with.",
        })
            y = Paragraph(pdf, y, p) + 4;
        y += 30;
        pdf.Line(Left, y, Left + 200, y, 0.6f); y += 14;
        pdf.Text(Left, y, "Authorised signatory", 10, bold: true); y += 13;
        pdf.Text(Left, y, "For and on behalf of " + entity.Name, 9.5f);
        brand.DrawFooter(pdf, Left, Right);
        return pdf.ToBytes();
    }

    /// <summary>Splits letter text into headings ("## "), bullets ("- ") and paragraphs (separated by blank lines).</summary>
    public static IEnumerable<(char Kind, string Text)> Blocks(string body)
    {
        var para = new List<string>();
        IEnumerable<(char, string)> Flush()
        {
            if (para.Count > 0) { yield return ('p', string.Join(' ', para)); para.Clear(); }
        }
        foreach (var raw in body.Replace("\r", "").Split('\n'))
        {
            var line = raw.Trim();
            if (line.Length == 0) { foreach (var b in Flush()) yield return b; continue; }
            if (line.StartsWith("## ")) { foreach (var b in Flush()) yield return b; yield return ('h', line[3..].Trim()); continue; }
            if (line.StartsWith("- ") || line.StartsWith("* ")) { foreach (var b in Flush()) yield return b; yield return ('-', line[2..].Trim()); continue; }
            para.Add(line);
        }
        foreach (var b in Flush()) yield return b;
    }
}
